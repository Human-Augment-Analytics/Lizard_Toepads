"""Map a Template_Record to the existing card_ocr layout and rules shapes.

The field pipeline (goal #3) consumes a ``fields.json`` layout via
``card_ocr.fields.load_layout``, an ``ocr_rules.json`` for extraction, and an
optional ``checkboxes`` section via ``card_ocr.fields.load_checkboxes``. These
helpers emit those shapes directly from a Template_Record so the template binds
without hand-reshaping.

Crop routing follows ``FieldSpec.crop_type``: ``"field"`` crops go to the OCR
fields layout and rules; ``"checkbox"`` crops (non-OCR: checkbox / pixel
intensity) go to the checkboxes layout only. Dictionary values are carried
through verbatim for the OCR stage to resolve (this module does not load or
validate them).
"""

from __future__ import annotations

from .template_record import TemplateRecord


def to_fields_layout(record: TemplateRecord) -> dict:
    """Return a dict matching template/fields.json: ``{"fields": [{name, box}, ...]}``.

    Only ``crop_type == "field"`` boxes are included. The output is accepted
    unchanged by ``card_ocr.fields.load_layout``.
    """
    return {
        "description": "Generated by template_builder from a Template_Record.",
        "fields": [
            {"name": spec.name, "box": list(spec.box)}
            for spec in record.fields if spec.is_field
        ],
    }


def to_checkboxes_layout(record: TemplateRecord) -> dict:
    """Return a dict matching the ``checkboxes`` section of the card layout.

    Only ``crop_type == "checkbox"`` boxes are included. The output is accepted
    by ``card_ocr.fields.load_checkboxes``.
    """
    return {
        "checkboxes": [
            {"name": spec.name, "box": list(spec.box)}
            for spec in record.fields if spec.is_checkbox
        ],
    }


def to_ocr_rules(record: TemplateRecord) -> dict:
    """Return an ``ocr_rules.json``-style skeleton keyed by field name.

    Only OCR (``crop_type == "field"``) boxes are included. Each entry carries
    the field ``type`` (datatype) and, when set, the recognition ``dictionary``
    carried verbatim from the template. Pattern/min/max tuning is left to the
    OCR stage.
    """
    fields: dict[str, dict] = {}
    for spec in record.fields:
        if not spec.is_field:
            continue
        entry: dict = {"type": spec.datatype}
        if spec.dictionary is not None:
            entry["dictionary"] = spec.dictionary
        fields[spec.name] = entry
    return {"fields": fields}
